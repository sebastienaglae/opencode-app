const dicts: Record<Lang, Dict> = { fr, en, ja };

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const value = dicts[lang]?.[key] ?? dicts.en[key] ?? key;
  return interpolate(value, vars);
}

/** Reactive translator bound to the current language setting. */
export function useT() {
  const lang = useSettings((s) => s.lang);
  return useMemo(() => (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
}

